const categories = ["Giao tiếp hằng ngày", "Gia đình", "Thói quen", "Ăn uống", "Du lịch", "Công sở"];

function toSentence(seed: Seed, index: number, level: "A1" | "A2"): Sentence {
  const [english, vietnamese, alternatives = [], note = "Mẫu câu giao tiếp tự nhiên"] = seed;
  return {
    id: `sentence_${String(index + 1).padStart(3, "0")}`,
    english,
    vietnamese,
    ipa: index === 0 ? "/aɪ æm ˌvjet.nəˈmiːz/" : "",
    level,
    category: categories[index % categories.length],
    lesson: `${level} - Bài ${String(Math.floor((index % 50) / 10) + 1).padStart(2, "0")}`,
    partOfSpeech: "",
    grammarNote: note,
    alternativeAnswers: alternatives,
    wordBank: english.replace(/[.!?]/g, "").split(/\s+/),
    audioUrl: "",
    tags: [level.toLowerCase(), categories[index % categories.length].toLowerCase()],
  };
}

function toDailySentence(seed: Seed, index: number): Sentence {
  const [english, vietnamese, alternatives = [], note = "Mẫu câu giao tiếp tự nhiên"] = seed;
  const lessonNum = Math.floor(index / 10) + 1;
  const lessonStr = `DAILY - Bài ${String(lessonNum).padStart(2, "0")}`;
  return {
    id: `sentence_daily_${String(index + 1).padStart(3, "0")}`,
    english,
    vietnamese,
    ipa: "",
    level: "A1–A2",
    category: categories[index % categories.length],
    lesson: lessonStr,
    partOfSpeech: "",
    grammarNote: note,
    alternativeAnswers: alternatives,
    wordBank: english.replace(/[.!?]/g, "").split(/\s+/),
    audioUrl: "",
    tags: ["daily", categories[index % categories.length].toLowerCase()],
  };
}

export const sentences: Sentence[] = [
  ...a1.map((seed, index) => toSentence(seed, index, "A1")),
  ...a2.map((seed, index) => toSentence(seed, index + 50, "A2")),
  ...daily.map((seed, index) => toDailySentence(seed, index)),
];
